object BasicSyntax {

    /**
     * Задача 1.1. Приветствие пользователя.
     *
     * Формирует строку с персональным приветствием и расчётом возраста через 10 лет.
     *
     * @param name Имя пользователя.
     * @param age Текущий возраст (в годах).
     * @return Строка с приветствием и возрастом через 10 лет.
     *
     * Пример: `greetUser("Анна", 25)` -> `"Привет, Анна! Через 10 лет тебе будет 35 лет."`
     */
    fun greetUser(name: String, age: Int): String {
        val futureAge = age + 10
        return "Привет, $name! Через 10 лет тебе будет $futureAge лет."
    }

    /**
     * Задача 1.2. Определение времени года по номеру месяца.
     *
     * Анализирует номер месяца (1–12) и возвращает соответствующее время года:
     * - 12, 1, 2: "Зима"
     * - 3, 4, 5: "Весна"
     * - 6, 7, 8: "Лето"
     * - 9, 10, 11: "Осень"
     * В случае некорректного значения возвращает "Некорректный месяц".
     *
     * @param month Порядковый номер месяца в году (1–12).
     * @return Название времени года или "Некорректный месяц".
     *
     * Пример: `getSeason(3)` -> `"Весна"`
     */
    fun getSeason(month: Int): String {
        return when (month) {
            12, 1, 2 -> "Зима"
            3, 4, 5 -> "Весна"
            6, 7, 8 -> "Лето"
            9, 10, 11 -> "Осень"
            else -> "Некорректный месяц"
        }
    }

    /**
     * Задача 1.3. Вычисление факториала числа с использованием хвостовой рекурсии (tailrec).
     *
     * Хвостовая рекурсия оптимизируется компилятором Kotlin в эффективный цикл
     * без риска возникновения ошибки `StackOverflowError`.
     * Для отрицательных чисел возвращается -1L.
     *
     * @param n Исходное целое число.
     * @param accumulator Промежуточный аккумулятор произведения (по умолчанию 1L).
     * @return Факториал числа n! или -1L при n < 0.
     *
     * Пример: `factorial(5)` -> `120L`
     */
    tailrec fun factorial(n: Int, accumulator: Long = 1L): Long {
        return when {
            n < 0 -> -1L
            n == 0 || n == 1 -> accumulator
            else -> factorial(n - 1, accumulator * n)
        }
    }
}
