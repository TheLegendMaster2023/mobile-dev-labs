package tasks

import kotlinx.coroutines.*

/**
 * Блок задач по асинхронному программированию с использованием Kotlin Coroutines.
 *
 * @author Мухамеджанов Эльёр Тимурович (ПИН-б-о-24-1 (2))
 * @version 1.0
 * @since 2026-09-03
 */
object Coroutines {

    /**
     * Задача 4.1. Асинхронная задержка с последовательным выводом сообщений.
     *
     * Выводит начальное сообщение, приостанавливает выполнение корутины на [delayMs]
     * миллисекунд с помощью неблокирующей функции [delay], после чего выводит строку "Готово!".
     *
     * @param message Исходное сообщение для печати в консоль.
     * @param delayMs Длительность паузы в миллисекундах.
     */
    suspend fun delayedPrint(message: String, delayMs: Long) {
        println(message)
        delay(delayMs)
        println("Готово!")
    }

    /**
     * Задача 4.2. Параллельное выполнение трёх асинхронных задач.
     *
     * Запускает три корутины параллельно с различными временами задержки (1с, 2с, 3с),
     * дожидается их завершения и возвращает собранные результаты.
     *
     * Благодаря параллельному выполнению через [async] общее время работы
     * составляет время самой длительной задачи (3 секунды), а не их сумму (6 секунд).
     *
     * @return Список строковых результатов в порядке завершения задач:
     * `["Результат 1", "Результат 2", "Результат 3"]`.
     */
    suspend fun runParallelTasks(): List<String> = coroutineScope {
        val task1 = async {
            delay(1000L)
            "Результат 1"
        }
        val task2 = async {
            delay(2000L)
            "Результат 2"
        }
        val task3 = async {
            delay(3000L)
            "Результат 3"
        }

        // Ожидаем завершения всех параллельных задач
        listOf(task1.await(), task2.await(), task3.await())
    }
}
